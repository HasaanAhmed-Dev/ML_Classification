"""
Stage 9 helper - fills the generated Angular app with OUR form.

Run from the project root AFTER `ng new frontend ...` and AFTER backend/make_payload.py:
    python setup_frontend.py

It (1) copies the files in frontend_overlay/ into frontend/ and (2) generates
frontend/src/app/feature-schema.ts and sample-flows.ts from backend/feature_schema.json
and backend/sample_flows.json, so the form always matches the model's exact features.
"""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent
FRONTEND = ROOT / "frontend"
APP = FRONTEND / "src" / "app"


def fmt(x):
    return f"{x:.4g}"


def main():
    if not (FRONTEND / "package.json").exists():
        raise SystemExit("frontend/ not found. Run `ng new frontend --routing --style=css --skip-git --defaults` first.")
    schema_path = ROOT / "backend" / "feature_schema.json"
    flows_path = ROOT / "backend" / "sample_flows.json"
    if not schema_path.exists() or not flows_path.exists():
        raise SystemExit("Run `python backend/make_payload.py` first.")

    overlay = ROOT / "frontend_overlay"
    for src in overlay.rglob("*"):
        if src.is_file():
            dest = FRONTEND / src.relative_to(overlay)
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(src, dest)
    spec = APP / "app.spec.ts"       # the generated placeholder test no longer matches our page
    if spec.exists():
        spec.unlink()

    schema = json.loads(schema_path.read_text(encoding="utf-8"))
    lines = ["// GENERATED by setup_frontend.py from backend/feature_schema.json - do not edit by hand.",
             "export type Feature = { name: string; label: string; hint: string };", "",
             "export const FEATURES: Feature[] = ["]
    for f in schema:
        hint = f"typical {fmt(f['p01'])} to {fmt(f['p99'])}"
        lines.append(f"  {{ name: {json.dumps(f['name'])}, label: {json.dumps(f['name'])}, hint: {json.dumps(hint)} }},")
    lines.append("];")
    (APP / "feature-schema.ts").write_text("\n".join(lines) + "\n", encoding="utf-8")

    flows = json.loads(flows_path.read_text(encoding="utf-8"))
    out = ["// GENERATED by setup_frontend.py from backend/sample_flows.json - do not edit by hand.",
           "export type SampleFlow = {", "  label: string;", "  values: Record<string, number>;",
           "  prediction: string;", "  confidence: number;", "  probabilities: Record<string, number>;", "};", "",
           "export const SAMPLE_FLOWS: SampleFlow[] = " + json.dumps(flows, indent=2) + ";"]
    (APP / "sample-flows.ts").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Frontend files written: {len(schema)} features, {len(flows)} example flows.")


if __name__ == "__main__":
    main()
